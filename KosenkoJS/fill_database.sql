-- Скрипт для создания и заполнения базы данных proxy_xim тестовыми данными
-- Выполнить: psql -d proxy_xim -U matvejvasilenko -f fill_database.sql

-- =========================
-- Удаление всех таблиц (если существуют)
-- =========================
DROP TABLE IF EXISTS productionreportmaterials CASCADE;
DROP TABLE IF EXISTS productionreportproducts CASCADE;
DROP TABLE IF EXISTS productionreportheaders CASCADE;
DROP TABLE IF EXISTS proxybodies CASCADE;
DROP TABLE IF EXISTS proxyheaders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS units CASCADE;
DROP TABLE IF EXISTS individuals CASCADE;
DROP TABLE IF EXISTS organizations CASCADE;

-- =========================
-- Создание таблиц
-- =========================

-- Таблица организаций
CREATE TABLE organizations (
    id SERIAL PRIMARY KEY,
    title VARCHAR(50) NOT NULL,
    inn VARCHAR(10) NOT NULL
);

-- Таблица физических лиц
CREATE TABLE individuals (
    id SERIAL PRIMARY KEY,
    "firstName" VARCHAR(25) NOT NULL,
    "lastName" VARCHAR(25) NOT NULL,
    patronymic VARCHAR(25),
    issued VARCHAR(80) NOT NULL,
    series VARCHAR(4) NOT NULL,
    number VARCHAR(6) NOT NULL
);

-- Таблица товаров
CREATE TABLE products (
    id SERIAL PRIMARY KEY,
    title VARCHAR(50) NOT NULL
);

-- Таблица единиц измерения
CREATE TABLE units (
    id SERIAL PRIMARY KEY,
    title VARCHAR(50) NOT NULL
);

-- Таблица заголовков доверенностей
CREATE TABLE proxyheaders (
    id SERIAL PRIMARY KEY,
    number INTEGER NOT NULL,
    "dischargeDate" DATE NOT NULL,
    "endDate" DATE NOT NULL,
    "individualId" INTEGER NOT NULL,
    "organizationId" INTEGER NOT NULL,
    status VARCHAR(20) DEFAULT 'active',
    "issuedBy" VARCHAR(255),
    notes TEXT,
    "passportNumber" VARCHAR(50),
    FOREIGN KEY ("individualId") REFERENCES individuals(id),
    FOREIGN KEY ("organizationId") REFERENCES organizations(id)
);

-- Таблица тел доверенностей
CREATE TABLE proxybodies (
    id SERIAL PRIMARY KEY,
    count INTEGER DEFAULT 1,
    unit VARCHAR(8) NOT NULL,
    "proxyHeaderId" INTEGER NOT NULL,
    "productId" INTEGER NOT NULL,
    price DECIMAL(10, 2) DEFAULT 0,
    FOREIGN KEY ("proxyHeaderId") REFERENCES proxyheaders(id) ON DELETE CASCADE,
    FOREIGN KEY ("productId") REFERENCES products(id)
);

-- Таблица заголовков отчетов производства за смену
CREATE TABLE productionreportheaders (
    id SERIAL PRIMARY KEY,
    number INTEGER NOT NULL,
    "reportDate" DATE NOT NULL,
    "organizationId" INTEGER NOT NULL,
    "okudCode" VARCHAR(20) DEFAULT '0335018',
    "okpoCode" VARCHAR(20),
    "okdpCode" VARCHAR(50),
    "operationType" VARCHAR(100),
    shift VARCHAR(50),
    "materialResponsibleId" INTEGER,
    "controllerId" INTEGER,
    "recipientId" INTEGER,
    notes TEXT,
    FOREIGN KEY ("organizationId") REFERENCES organizations(id),
    FOREIGN KEY ("materialResponsibleId") REFERENCES individuals(id),
    FOREIGN KEY ("controllerId") REFERENCES individuals(id),
    FOREIGN KEY ("recipientId") REFERENCES individuals(id)
);

-- Таблица продукции в отчете производства
CREATE TABLE productionreportproducts (
    id SERIAL PRIMARY KEY,
    "productionReportHeaderId" INTEGER NOT NULL,
    "productName" VARCHAR(255) NOT NULL,
    "productCode" VARCHAR(50),
    "unitCode" VARCHAR(20),
    unit VARCHAR(50),
    "quantityPlace" DECIMAL(10, 3),
    "quantityPlaces" INTEGER,
    "grossWeight" DECIMAL(10, 3),
    "netWeight" DECIMAL(10, 3),
    price DECIMAL(10, 2),
    "totalAmount" DECIMAL(12, 2),
    FOREIGN KEY ("productionReportHeaderId") REFERENCES productionreportheaders(id) ON DELETE CASCADE
);

-- Таблица материалов в отчете производства
CREATE TABLE productionreportmaterials (
    id SERIAL PRIMARY KEY,
    "productionReportHeaderId" INTEGER NOT NULL,
    "accountCode" VARCHAR(20),
    "accountSubcode" VARCHAR(50),
    "materialName" VARCHAR(255) NOT NULL,
    "nomenclatureCode" VARCHAR(50),
    "unitCode" VARCHAR(20),
    unit VARCHAR(50),
    requested DECIMAL(10, 3),
    issued DECIMAL(10, 3),
    price DECIMAL(10, 2),
    "totalAmountNoVAT" DECIMAL(12, 2),
    "warehouseCardNumber" VARCHAR(50),
    FOREIGN KEY ("productionReportHeaderId") REFERENCES productionreportheaders(id) ON DELETE CASCADE
);

